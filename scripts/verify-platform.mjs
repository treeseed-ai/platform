import { existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const fail = (message) => { throw new Error(message); };
if (existsSync(resolve(root, '.gitmodules'))) fail('Platform must not encode its portfolio as gitlinks.');
const portfolio = JSON.parse(readFileSync(resolve(root, 'treeseed.portfolio.json'), 'utf8'));
if (portfolio.kind !== 'treeseed.portfolio' || portfolio.schemaVersion !== 1) fail('Platform portfolio contract is invalid.');
const repositories = Array.isArray(portfolio.repositories) ? portfolio.repositories : [];
if (repositories.length !== 13) fail(`Expected 13 federated project/fixture repositories, found ${repositories.length}.`);
if (repositories.some((entry) => /treeseed-ai\/(market|market-api)$/u.test(entry.repository))) fail('Platform portfolio contains Market.');
if (repositories.some((entry) => /-content$/u.test(entry.repository))) fail('Platform portfolio materializes a content repository.');
if (repositories.some((entry) => !/^[a-f0-9]{40}$/u.test(entry.commit))) fail('Platform portfolio contains a non-exact repository ref.');
const paths = new Set(repositories.map((entry) => entry.path));
if (paths.size !== repositories.length) fail('Platform portfolio contains duplicate workset paths.');
const config = readFileSync(resolve(root, 'treeseed.site.yaml'), 'utf8');
const requiredConfig = [/^\s*kind: customer-platform\s*$/mu, /^\s*profile: treeseed\s*$/mu, /^\s*mode: market-passthrough\s*$/mu, /^runtime:\s*\n\s+mode: none\s*$/mu, /^\s*enabled: false\s*$/mu, /^services: \{\}\s*$/mu];
if (requiredConfig.some((pattern) => !pattern.test(config))) fail('Platform configuration does not preserve its non-hosted customer authority and singleton Market binding.');
if (/^\s*market-?api:/imu.test(config)) fail('Platform configuration declares a forbidden Market API service.');
const seed = readFileSync(resolve(root, 'seeds/treeseed.yaml'), 'utf8');
if (/^\s+slug: market(?:-api)?\s*$/mu.test(seed)) fail('Platform seed declares a Market project.');
if (/information-hub/iu.test(seed)) fail('Platform seed contains a retired repository identity.');
console.log(JSON.stringify({ ok: true, repositories: repositories.length, gitlinks: 0, marketCheckouts: 0, authority: 'customer-platform', marketProfile: 'treeseed', hostedSurfaces: 0 }));
